#!/usr/bin/env python3
"""Table of the Shtrih-M (POScenter fr_drv_ng) C interface for src/shtrih_api.inc.

Usage: scripts/gen-shtrih-api.py <path to c_classic_interface.h> > src/shtrih_api.inc

The header ships with the driver (dist/<platform>/c_classic_interface.h). Only
names and value types are taken from it: properties (Set_X / Get_X) and methods
(int X(ctx)). Type letters: i int/enum, b bool, s string (UTF-8), l int64,
u uint32, t time_t, q uint64, d double, y bytes.
"""
import re, sys

src = re.sub(r'\s+', ' ', open(sys.argv[1], encoding='utf-8', errors='ignore').read())
decls = re.findall(r'C_CLASSIC_FR_DRV_NG_API ([^;{]+?\));', src)
CTX = r'\s*c_classic_context_t\s*\*\s*ctx'
SET_T = {'int': 'i', 'bool': 'b', 'int64_t': 'l', 'uint32_t': 'u', 'time_t': 't', 'uint64_t': 'q', 'double': 'd'}
GET_T = dict(SET_T)

props, methods = {}, []
for d in decls:
    m = re.fullmatch(r'void Set_(\w+)\(' + CTX + r',\s*(.+)\)', d)
    if m:
        name, arg = m.groups()
        if re.fullmatch(r'const char\s*\*\s*value,\s*size_t len', arg): t = 's'
        elif re.fullmatch(r'const uint8_t\s*\*\s*value,\s*size_t len', arg): t = 'y'
        else:
            typ = arg.rsplit(' ', 1)[0].strip()
            t = SET_T.get(typ, 'i' if typ.startswith('T') else None)
        if t: props.setdefault(name, ['0', '0'])[0] = t
        continue
    m = re.fullmatch(r'(\w+) Get_(\w+)\(' + CTX + r'(.*)\)', d)
    if m:
        ret, name, rest = m.groups()
        if 'char* out_value' in rest.replace(' *', '*'): t = 's'
        elif 'uint8_t* out_value' in rest.replace(' *', '*'): t = 'y'
        elif rest.strip(): t = None
        else: t = GET_T.get(ret, 'i' if ret.startswith('T') else None)
        if t: props.setdefault(name, ['0', '0'])[1] = t
        continue
    m = re.fullmatch(r'int (\w+)\(' + CTX + r'\)', d)
    if m and not m.group(1).startswith(('Get_', 'Set_')):
        methods.append(m.group(1))

print('// Generated by scripts/gen-shtrih-api.py from c_classic_interface.h — do not edit.')
print('// { name, setter type, getter type } — see the script for the type letters.')
print('static const ShtrihProp kShtrihProps[] = {')
for n in sorted(props):
    s, g = props[n]
    print(f'  {{"{n}", \'{s}\', \'{g}\'}},'.replace("'0'", '0'))
print('};')
print('static const char *const kShtrihMethods[] = {')
for n in sorted(set(methods)):
    print(f'  "{n}",')
print('};')
